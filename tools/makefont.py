ACC = {  # (base, filas de acento sobre la letra: 2 filas)
 'Á':('A',('..#..','.#...')),'É':('E',('..#..','.#...')),'Í':('I',('..#..','.#...')),'Ó':('O',('..#..','.#...')),'Ú':('U',('..#..','.#...')),
 'Ü':('U',('.#.#.','.....')),'Ñ':('N',('.#.#.','#.#..')),
}
INV = {'¿':'?', '¡':'!'}

U = 100  # unidades por píxel (em = 1000 -> 10px), alto de 9 filas
ASC, DESC = 800, 200
def bounds(rows, extra=None):
    cols = [x for r in list(rows) + list(extra or []) for x in range(5) if r[x] == '#']
    return (min(cols), max(cols)) if cols else (0, 0)
def build_glyph(rows, top_extra=None, flip=False):
    pen = TTGlyphPen(None)
    mn, mx = bounds(rows, top_extra)
    allrows = list(rows)
    if flip: allrows = allrows[::-1]
    # y=0 es la línea base; la fila 0 del bitmap va arriba (7 filas => 700)
    base_h = 7
    for r, row in enumerate(allrows):
        y = (base_h - 1 - r) * U
        x = 0
        while x < 5:
            if row[x] == '#':
                e = x
                while e < 5 and row[e] == '#': e += 1
                pen.moveTo(((x-mn)*U, y)); pen.lineTo(((x-mn)*U, y+U)); pen.lineTo(((e-mn)*U, y+U)); pen.lineTo(((e-mn)*U, y)); pen.closePath()
                x = e
            else: x += 1
    if top_extra:
        for r, row in enumerate(top_extra):
            y = (base_h + 1 - r) * U  # sobre la fila 7 con un hueco de 0
            x = 0
            while x < 5:
                if row[x] == '#':
                    e = x
                    while e < 5 and row[e] == '#': e += 1
                    pen.moveTo(((x-mn)*U, y)); pen.lineTo(((x-mn)*U, y+U)); pen.lineTo(((e-mn)*U, y+U)); pen.lineTo(((e-mn)*U, y)); pen.closePath()
                    x = e
                else: x += 1
    return pen.glyph()
def width_of(rows, extra=None):
    if all(c == '.' for r in rows for c in r): return 4 * U
    mn, mx = bounds(rows, extra)
    return (mx - mn + 2) * U

glyphs = {'.notdef': build_glyph(G['?'])}
cmap = {}
order = ['.notdef']
WID = {}
def add(name, cp, glyph, w=6*U):
    glyphs[name] = glyph; cmap[cp] = name; WID[name] = w
    if name not in order: order.append(name)
for ch, rows in G.items():
    add('u%04X' % ord(ch), ord(ch), build_glyph(rows), width_of(rows))
    if ch.isalpha() and ch.isascii():   # minúsculas = mayúsculas (estilo de cartel)
        add('u%04X' % ord(ch.lower()), ord(ch.lower()), build_glyph(rows), width_of(rows))
for ch, (b, acc) in ACC.items():
    add('u%04X' % ord(ch), ord(ch), build_glyph(G[b], acc), width_of(G[b], acc))
    add('u%04X' % ord(ch.lower()), ord(ch.lower()), build_glyph(G[b], acc), width_of(G[b], acc))
add('u00BF', 0xBF, build_glyph(G['?'], flip=True), width_of(G['?']))
add('u00A1', 0xA1, build_glyph(G['!'], flip=True), width_of(G['!']))
# dedupe cmap duplicates safe
adv = 6 * U
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf({n: glyphs[n] for n in order})
fb.setupHorizontalMetrics({n: (WID.get(n, adv), 0) for n in order})
fb.setupHorizontalHeader(ascent=ASC+100, descent=-ASC//4)
fb.setupNameTable({'familyName': 'CasinoPixel', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=ASC+100, sTypoDescender=-ASC//4, usWinAscent=1000, usWinDescent=250)
fb.setupPost()
out = os.path.join(os.path.dirname(__file__), '..', 'public', 'fonts', 'pixel.ttf')
fb.save(out)
